package com.arijit.arceus.events.otp;

import java.io.Serializable;
import java.util.UUID;

/**
 * The envelope that travels over RabbitMQ from auth-service to
 * notification-service. otpCode is only populated for EMAIL - see
 * notification-service's PhoneOtpSender for why SMS is asymmetric
 * (2Factor generates its own code, we never have one to pass along).
 * <p>
 * {@code messageId} is an idempotency key: RabbitMQ redelivers on crash/nack,
 * and without something stable to dedupe on, a redelivered message would
 * send the same OTP email/SMS twice. Generated once at publish time via
 * {@link #of}, never regenerated by the consumer.
 */
public record OtpNotificationMessage(
        String messageId,
        OtpChannel channel,
        String recipient,
        String otpCode,
        OtpPurpose purpose,
        String recipientName
) implements Serializable {

    public static OtpNotificationMessage of(OtpChannel channel, String recipient, String otpCode,
                                             OtpPurpose purpose, String recipientName) {
        return new OtpNotificationMessage(UUID.randomUUID().toString(), channel, recipient, otpCode, purpose, recipientName);
    }
}
